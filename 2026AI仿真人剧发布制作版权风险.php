四、风险边界：未经授权的法律与商业风险

版权侵权风险

改编权是《中华人民共和国著作权法》规定的著作权人专有权利之一。未经权利人许可，擅自将网络小说改编为短剧，同时侵害改编权、摄制权和信息网络传播权三项权利，法律后果非常严重。

判断短剧是否侵犯网络小说的著作权，关键在于判断短剧是否接触了网络小说并提取、再现了小说的独创性核心——如驱动故事核心情节的序列（人物设置与人物关系，推动故事发展主线各个环节的选择、编排）及其具体的视听呈现方式（标志性的台词、独特细节、标志性场景等），而非逐句逐字比对。若上述表达高度一致，即可认定二者构成"实质性相似"，侵权成立。

已判决的赔偿金额

司法实践中，未经授权改编短剧的赔偿数额已相当高：

· 2025年10月，宁波中院判决《将军！夫人她请旨和离了》擅自改编《桃花马上请长缨》构成侵权，赔偿25万元（含合理维权费用），三关联公司承担连带责任。
· 2026年杭州互联网法院判决短剧《愿君安宁》擅自改编盐言故事《岁岁无虞》，赔偿20万元。
· 某短剧擅自改编七猫平台小说，赔偿60余万元。

平台方的主动维权与整治行动

番茄小说于2026年5月底发布《番茄小说原创作者版权维权指引》，针对未经授权擅自使用平台作品改编、制作并发行微短剧的侵权行为，开展专项整治行动。近两周，平台已完成300余部微短剧（包含AI短剧、真人短剧）的事实核查与侵权认定工作，其中70余部作品确认侵权并达成赔偿方案，累计赔偿款280万余元，单部最高赔付超50万元。

这意味着，即便权利人未主动起诉，平台自身也在主动识别和打击侵权内容，侵权者面临被平台封禁和追偿的双重风险。

创作中的避坑要点

· 不要直接联系作者私下要授权——番茄等平台的小说IP大多是平台独家授权给平台的，个人私下找作者拿的授权无法覆盖平台的版权权益，必须走官方渠道。
· 签约协议中要写清楚AI生成、二次创作都在授权范围内，避免后续扯皮。
· 不要"洗稿"或"换皮"——即便不逐字照抄，如果提取了小说的独创性核心情节和人物关系，同样构成侵权。
· 拒绝私下交易、无资质代投，谨防骗稿。
· 一稿一投，未签约前不公开上传。

五、总结

个人创作者合法改编红果/番茄小说的必经路径是：入驻短剧创作者中心 → 完成实名认证 → 在IP版权专区申请授权 → 审核通过签订合同 → 制作成片后上传平台。番茄小说的IP改编权已高度集中在官方授权池中，平台通过合作模式（模式二、模式三）和月度申请配额来管理授权准入，目前对个人创作者每月开放1部网文+5部短篇的申请额度，经评估优质产出可动态调整。

2025-2026年多起短剧侵权案已判赔20万-60余万元，番茄官方也正在大规模主动维权（单部最高赔付超50万元），未取得官方授权擅自改编，无论采取何种规避手段，都有极高的法律和商业风险。合规改编，走官方授权池，是个人创作者最稳妥、成本最低的路径。



结论：个人创作者不能自己随便拿红果/番茄小说来改编；必须走平台官方授权池，拿到改编权，否则就是侵权。下面把“在哪找、怎么申请、哪些能改、风险边界”讲清楚。
 
 
 
 
 
 
 
 
